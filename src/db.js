function databaseUrl() {
  const url = (process.env.DATABASE_URL || '').trim();
  return url || null;
}

function isPlainObject(v) {
  return v !== null && typeof v === 'object' && !Array.isArray(v) && Object.getPrototypeOf(v) === Object.prototype;
}

function clean(v) { return v === undefined ? null : v; }

/** Hostname of a postgres URL, even when the password is not percent-encoded. */
function hostnameOf(connectionString) {
  try { return new URL(connectionString).hostname.toLowerCase(); }
  catch {
    const m = String(connectionString).match(/@([^/?\s]+)(?:[/?]|$)/);
    if (!m) return '';
    const hostport = m[1];
    if (hostport.startsWith('[')) {
      const end = hostport.indexOf(']');
      return (end === -1 ? hostport.slice(1) : hostport.slice(1, end)).toLowerCase();
    }
    return hostport.split(':')[0].toLowerCase();
  }
}

/**
 * SSL for Render: external hostnames (*.render.com) need TLS and use a
 * certificate chain Node does not treat as public, so rejectUnauthorized is
 * false. Internal hostnames (no ".render.com") stay on the private network
 * without SSL. DATABASE_SSL forces either mode.
 */
function sslForUrl(connectionString, flag = process.env.DATABASE_SSL) {
  const f = String(flag ?? '').trim().toLowerCase();
  if (['0', 'false', 'off', 'disable', 'no'].includes(f)) return false;
  if (['1', 'true', 'on', 'require', 'yes'].includes(f)) return { rejectUnauthorized: false };
  const host = hostnameOf(connectionString);
  if (host.includes('.render.com')) return { rejectUnauthorized: false };
  return false;
}

function stripSslMode(connectionString) {
  return String(connectionString)
    .replace(/([?&])sslmode=[^&]*&/gi, '$1')
    .replace(/([?&])sslmode=[^&]*$/gi, '')
    .replace(/[?&]$/, '');
}

function connectionOptions(connectionString, extra = {}) {
  return {
    connectionString: stripSslMode(connectionString),
    ssl: sslForUrl(connectionString),
    ...extra,
  };
}

function splitSql(sql) {
  const out = [];
  let buf = '';
  let inSingle = false;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'" && inSingle && sql[i + 1] === "'") { buf += "''"; i++; continue; }
    if (c === "'") { inSingle = !inSingle; buf += c; continue; }
    if (c === ';' && !inSingle) {
      if (buf.trim()) out.push(buf.trim());
      buf = '';
      continue;
    }
    buf += c;
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

/**
 * `?` and `@name` (SQLite) → `$1` (Postgres). LIKE becomes ILIKE so ASCII
 * searches stay case-insensitive, matching SQLite's default LIKE.
 */
function compile(sql, args, driver) {
  const named = args.length === 1 && isPlainObject(args[0]);
  if (driver === 'sqlite') {
    if (named) {
      const obj = {};
      for (const [k, v] of Object.entries(args[0])) obj[k] = clean(v);
      return { sql, params: obj, mode: 'named' };
    }
    return { sql, params: args.map(clean), mode: 'positional' };
  }
  const positional = named ? null : args.map(clean);
  const values = [];
  let pi = 0;
  const text = sql.replace(/'(?:''|[^'])*'|@([A-Za-z_][\w]*)|\?/g, (m, name) => {
    if (m[0] === "'") return m;
    if (name) {
      if (!named || !Object.prototype.hasOwnProperty.call(args[0], name)) {
        throw new Error(`Parâmetro @${name} em falta`);
      }
      values.push(clean(args[0][name]));
    } else {
      if (!positional || pi >= positional.length) throw new Error('Parâmetro posicional em falta');
      values.push(positional[pi++]);
    }
    return `$${values.length}`;
  });
  const translated = text.replace(/'(?:''|[^'])*'|\bLIKE\b/gi, (m) => (m[0] === "'" ? m : 'ILIKE'));
  return { sql: translated, params: values, mode: 'pg' };
}

function apartmentSort(driver, column = 'apartamento') {
  if (!/^[A-Za-z_][\w.]*$/.test(column)) throw new Error('Coluna inválida');
  if (driver === 'postgres') return `(CASE WHEN ${column} ~ '^[0-9]+$' THEN ${column}::integer ELSE 0 END)`;
  return `CAST(${column} AS INTEGER)`;
}

function isUniqueViolation(err) {
  return !!err && (err.code === '23505' || /UNIQUE constraint failed/i.test(err.message || ''));
}

function bindSqlite(stmt, compiled, method) {
  if (compiled.mode === 'named') return stmt[method](compiled.params);
  if (!compiled.params.length) return stmt[method]();
  return stmt[method](...compiled.params);
}

function makeSqlite(raw) {
  let chain = Promise.resolve();
  function enqueue(fn) {
    const run = chain.then(fn);
    chain = run.then(() => {}, () => {});
    return run;
  }
  function direct() {
    return {
      async get(sql, ...args) {
        const compiled = compile(sql, args, 'sqlite');
        const row = bindSqlite(raw.prepare(compiled.sql), compiled, 'get');
        return row === undefined ? undefined : row;
      },
      async all(sql, ...args) {
        const compiled = compile(sql, args, 'sqlite');
        return bindSqlite(raw.prepare(compiled.sql), compiled, 'all');
      },
      async run(sql, ...args) {
        const compiled = compile(sql, args, 'sqlite');
        const info = bindSqlite(raw.prepare(compiled.sql), compiled, 'run');
        return { lastInsertRowid: Number(info.lastInsertRowid), changes: info.changes };
      },
      async exec(sql) { raw.exec(sql); },
    };
  }
  const db = {
    driver: 'sqlite',
    apartmentSort(column) { return apartmentSort('sqlite', column); },
    get(sql, ...args) { return enqueue(() => direct().get(sql, ...args)); },
    all(sql, ...args) { return enqueue(() => direct().all(sql, ...args)); },
    run(sql, ...args) { return enqueue(() => direct().run(sql, ...args)); },
    exec(sql) { return enqueue(() => direct().exec(sql)); },
    transaction(fn) {
      return enqueue(async () => {
        raw.exec('BEGIN IMMEDIATE');
        try {
          const result = await fn(direct());
          raw.exec('COMMIT');
          return result;
        } catch (err) {
          try { raw.exec('ROLLBACK'); } catch { /* já revertida */ }
          throw err;
        }
      });
    },
    close() {
      return enqueue(() => {
        if (db._closed) return;
        db._closed = true;
        raw.close();
      });
    },
  };
  return db;
}

function shouldReturnId(sql) {
  return /^\s*insert\s+into\s+(?!settings\b)/i.test(sql) && !/\breturning\b/i.test(sql);
}

function makePgApi(queryable) {
  return {
    async get(sql, ...args) {
      const compiled = compile(sql, args, 'postgres');
      const result = await queryable.query(compiled.sql, compiled.params);
      return result.rows[0];
    },
    async all(sql, ...args) {
      const compiled = compile(sql, args, 'postgres');
      const result = await queryable.query(compiled.sql, compiled.params);
      return result.rows;
    },
    async run(sql, ...args) {
      const compiled = compile(sql, args, 'postgres');
      let text = compiled.sql;
      if (shouldReturnId(text)) text += ' RETURNING id';
      const result = await queryable.query(text, compiled.params);
      const id = result.rows[0] && result.rows[0].id;
      return { lastInsertRowid: id == null ? undefined : Number(id), changes: result.rowCount };
    },
    async exec(sql) {
      for (const part of splitSql(sql)) await queryable.query(part);
    },
  };
}

function assertSchemaName(schema) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(schema)) throw new Error('Nome de schema inválido');
}

async function openPostgres(connectionString, opts = {}) {
  const schema = opts.schema || null;
  if (schema) assertSchemaName(schema);
  const base = connectionOptions(connectionString);
  if (schema) {
    const client = new pg.Client(base);
    await client.connect();
    try { await client.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`); }
    finally { await client.end(); }
  }
  const pool = new pg.Pool({
    ...base,
    max: opts.max || Number(process.env.DATABASE_POOL_MAX || 5),
    connectionTimeoutMillis: 10000,
    idleTimeoutMillis: 10000,
    ...(schema ? { options: `-c search_path=${schema}` } : {}),
  });
  const api = makePgApi(pool);
  for (const part of splitSql(SCHEMA_PG)) await pool.query(part);

  const db = {
    driver: 'postgres',
    file: null,
    apartmentSort(column) { return apartmentSort('postgres', column); },
    get: api.get,
    all: api.all,
    run: api.run,
    exec: api.exec,
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        try {
          const result = await fn(makePgApi(client));
          await client.query('COMMIT');
          return result;
        } catch (err) {
          try { await client.query('ROLLBACK'); } catch { /* já revertida */ }
          throw err;
        }
      } finally {
        client.release();
      }
    },
    async close() {
      if (db._closed) return;
      db._closed = true;
      await pool.end();
      if (schema && opts.dropSchema) {
        const client = new pg.Client(base);
        await client.connect();
        try { await client.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); }
        finally { await client.end(); }
      }
    },
  };
  return db;
}

async function openSqlite(file) {
  const target = file || process.env.DB_FILE || path.join(__dirname, '..', 'data', 'condominio.db');
  if (target !== ':memory:') fs.mkdirSync(path.dirname(path.resolve(target)), { recursive: true });
  const raw = new Database(target);
  raw.pragma('journal_mode = WAL');
  raw.pragma('foreign_keys = ON');
  raw.pragma('busy_timeout = 5000');
  raw.exec(SCHEMA_SQLITE);
  const db = makeSqlite(raw);
  db.file = target;
  return db;
}

/**
 * openDb() uses Postgres when DATABASE_URL is set, otherwise SQLite.
 * openDb(file) always opens SQLite (tests pass ':memory:').
 * openDb(null, { schema, dropSchema }) opens Postgres in an isolated schema.
 */
async function openDb(file, opts = {}) {
  const schema = opts.schema || (!file && process.env.DATABASE_SCHEMA) || null;
  const wantPg = !!(opts.postgres || schema || (!file && databaseUrl()));
  if (wantPg) {
    const url = databaseUrl();
    if (!url) throw new Error('DATABASE_URL não está definida.');
    return openPostgres(url, { ...opts, schema: schema || null });
  }
  return openSqlite(file);
}

async function getSetting(db, key) {
  const row = await db.get('SELECT value FROM settings WHERE key = ?', key);
  return row ? row.value : null;
}

async function setSetting(db, key, value) {
  await db.run(
    'INSERT INTO settings(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value',
    key, value,
  );
}

/** Insert only when missing, then return whatever row won the race. */
async function ensureSetting(db, key, generate) {
  const existing = await getSetting(db, key);
  if (existing) return existing;
  await db.run('INSERT INTO settings(key,value) VALUES(?,?) ON CONFLICT(key) DO NOTHING', key, generate());
  return getSetting(db, key);
}

